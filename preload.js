const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getInitial: () => ipcRenderer.invoke('get-initial'),
  setDirty: (d) => ipcRenderer.send('set-dirty', d),
  save: (content, saveAs, filePath) => ipcRenderer.invoke('save', { content, saveAs, filePath }),
  confirmSave: (name) => ipcRenderer.invoke('confirm-save', name),
  readDoc: (p) => ipcRenderer.invoke('read-doc', p),
  askReload: (name, dirty) => ipcRenderer.invoke('ask-reload', { name, dirty }),
  openDialog: () => ipcRenderer.invoke('open-dialog'),
  openPath: (p) => ipcRenderer.send('open-path', p),
  openLink: (href, base) => ipcRenderer.send('open-link', { href, base }),
  closeNow: () => ipcRenderer.send('close-now'),
  exportPdf: (filePath) => ipcRenderer.invoke('export-pdf', filePath),
  saveImage: (docPath, data, ext, srcPath) => ipcRenderer.invoke('save-image', { docPath, data, ext, srcPath }),
  menuModel: () => ipcRenderer.invoke('menu-model'),
  menuClick: (path) => ipcRenderer.send('menu-click', path),
  onMenuChanged: (fn) => ipcRenderer.on('menu-changed', (_e, m) => fn(m)),
  autosave: (filePath, content, mtime) => ipcRenderer.invoke('autosave', { filePath, content, mtime }),
  recoveryWrite: (key, data) => ipcRenderer.send('recovery-write', { key, data }),
  recoveryClear: (key) => ipcRenderer.send('recovery-clear', key),
  print: () => ipcRenderer.invoke('print'),
  contextMenu: (items) => ipcRenderer.invoke('context-menu', items),
  saveDiagram: (docPath, data, ext) => ipcRenderer.invoke('save-diagram', { docPath, data, ext }),
  fileTimes: (paths) => ipcRenderer.invoke('file-times', paths),
  newDrawio: (docPath) => ipcRenderer.invoke('new-drawio', docPath),
  editDrawio: (file) => ipcRenderer.invoke('edit-drawio', file),
  isDrawio: (files) => ipcRenderer.invoke('is-drawio', files),
  pickDrawio: () => ipcRenderer.invoke('pick-drawio'),
  pickImage: (docPath) => ipcRenderer.invoke('pick-image', docPath),
  pathForFile: (f) => webUtils.getPathForFile(f),
  onCommand: (fn) => ipcRenderer.on('cmd', (_e, c) => fn(c)),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  setTheme: (t) => ipcRenderer.send('set-theme', t),
  setSession: (tabs, active) => ipcRenderer.send('set-session', { tabs, active }),
  setSidebar: (open) => ipcRenderer.send('set-sidebar', open),
  removeRecent: (p) => ipcRenderer.send('remove-recent', p),
  onRecent: (fn) => ipcRenderer.on('recent', (_e, list) => fn(list)),
  onTheme: (fn) => ipcRenderer.on('theme', (_e, t) => fn(t)),
  onOpenFile: (fn) => ipcRenderer.on('open-file', (_e, f) => fn(f)),
});
